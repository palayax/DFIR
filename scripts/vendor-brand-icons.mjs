#!/usr/bin/env node
// Vendor a fixed subset of Simple Icons (CC0-1.0) into one ES module:
//   web/assets/vendor/simple-icons/brands.js   -> export const BRAND_ICONS = { slug: {title, hex, path, sha256} }
//
//   node scripts/vendor-brand-icons.mjs           # fetch the pinned version and (re)write the module
//   node scripts/vendor-brand-icons.mjs --check   # exit 1 if the module disagrees with the pinned upstream files
//
// The app must run air-gapped with no CDN at runtime, so the icons are fetched
// ONCE here (a deliberate, pinned, network step) and committed. Each icon keeps
// the SHA-256 of the exact upstream SVG it came from. Brand names and logos are
// trademarks of their owners; the ACME.Corp demo uses them only to depict a
// fictional company's technology stack.

import { createHash } from 'node:crypto';
import { writeFile, readFile, mkdir } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const VERSION = '16.32.0';
const BASE = `https://cdn.jsdelivr.net/npm/simple-icons@${VERSION}`;
const SLUGS = [
  'okta', 'github', 'githubactions', 'githubcopilot', 'jira', 'jfrog', 'vault', 'argo', 'splunk', 'cloudflare', 'qualys',
  'veeam', 'paloaltonetworks', 'cisco', 'googlecloud', 'googlebigquery', 'kubernetes', 'postgresql', 'claude', 'anthropic',
  'apple', 'ubuntu', 'redhat', 'stripe', 'zoom', 'hp', 'datadog', 'pagerduty', 'owasp', 'docker', 'terraform',
];
const HERE = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.join(HERE, '..', 'web', 'assets', 'vendor', 'simple-icons', 'brands.js');

const args = process.argv.slice(2);
if (args.some((a) => a !== '--check')) { console.error(`unknown argument(s): ${args.join(' ')}`); process.exit(2); }
const check = args.includes('--check');

async function get(url) {
  const r = await fetch(url);
  if (!r.ok) throw new Error(`${url}: HTTP ${r.status}`);
  return r.text();
}

const data = JSON.parse(await get(`${BASE}/data/simple-icons.json`));
const list = Array.isArray(data) ? data : data.icons;
const slugOf = (i) => i.slug || i.title.toLowerCase().replace(/\+/g, 'plus').replace(/[^a-z0-9]/g, '');
const meta = new Map(list.map((i) => [slugOf(i), i]));
const icons = {};
for (const slug of SLUGS) {
  const svg = await get(`${BASE}/icons/${slug}.svg`);
  const m = /<path d="([^"]+)"/.exec(svg);
  const t = /<title>([^<]+)<\/title>/.exec(svg);
  if (!m) throw new Error(`${slug}: no path in SVG`);
  const info = meta.get(slug);
  if (!info) throw new Error(`${slug}: not in data file`);
  icons[slug] = { title: t ? t[1] : info.title, hex: `#${info.hex}`, path: m[1], sha256: createHash('sha256').update(svg).digest('hex') };
}
const source = `// GENERATED by scripts/vendor-brand-icons.mjs -- do not edit by hand.
// Simple Icons ${VERSION} (https://simpleicons.org, CC0-1.0), ${SLUGS.length} icons.
// sha256 = hash of the exact upstream SVG file. Brand names and logos are
// trademarks of their respective owners; used to depict a fictional company's stack.
export const SIMPLE_ICONS_VERSION = '${VERSION}';
export const BRAND_ICONS = ${JSON.stringify(icons, null, 1)};
`;
if (check) {
  const cur = await readFile(OUT, 'utf8').catch(() => '');
  if (cur.replace(/\r\n/g, '\n') !== source) { console.error('brands.js is stale'); process.exit(1); }
  console.log('brands.js up to date');
} else {
  await mkdir(path.dirname(OUT), { recursive: true });
  await writeFile(OUT, source);
  console.log(`wrote ${OUT} (${SLUGS.length} icons)`);
}
